-- ---------- updated_at triggers ----------
do $$
declare t text;
begin
  foreach t in array array['tms_depots','tms_address_book','tms_drivers','tms_vehicles',
                           'tms_consignments','tms_checkin_sheets','tms_trips','tms_boards']
  loop
    execute format('drop trigger if exists %I on public.%I;', t||'_touch', t);
    execute format('create trigger %I before update on public.%I for each row execute function public.tms_touch_updated_at();', t||'_touch', t);
  end loop;
end $$;

