create or replace function public.tms_touch_updated_at() returns trigger
  language plpgsql as $$ begin new.updated_at = now(); return new; end; $$;

create table if not exists public.tms_consignment_seq (
  year int primary key, last_no int not null default 0
);

create or replace function public.tms_assign_consignment_no() returns trigger
  language plpgsql security definer set search_path = public as $$
declare y int; n int;
begin
  if new.consignment_no is null or new.consignment_no = '' then
    y := extract(year from now())::int;
    insert into public.tms_consignment_seq(year, last_no) values (y, 1)
      on conflict (year) do update set last_no = public.tms_consignment_seq.last_no + 1
      returning last_no into n;
    new.consignment_no := 'UBF-C-' || y || '-' || lpad(n::text, 4, '0');
  end if;
  return new;
end; $$;

