drop policy if exists driver_read_consignments on public.tms_consignments;
create policy driver_read_consignments on public.tms_consignments
  for select to authenticated
  using (assigned_driver_leg1 = public.tms_driver_id() or assigned_driver_leg2 = public.tms_driver_id());

drop policy if exists driver_update_consignments on public.tms_consignments;
create policy driver_update_consignments on public.tms_consignments
  for update to authenticated
  using (assigned_driver_leg1 = public.tms_driver_id() or assigned_driver_leg2 = public.tms_driver_id())
  with check (assigned_driver_leg1 = public.tms_driver_id() or assigned_driver_leg2 = public.tms_driver_id());

