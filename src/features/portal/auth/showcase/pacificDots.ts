/** Project lng/lat to SVG units (10 per grid cell). Longitudes west of 0 wrap east. */
export function project(lng: number, lat: number): [number, number] {
  const x = lng < 0 ? lng + 360 : lng
  return [((x - DOT_LNG0) / DOT_STEP) * 10 + 5, ((DOT_LAT0 - lat) / DOT_STEP) * 10 + 5]
}
